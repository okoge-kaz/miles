#!/bin/bash
# Fixed-name configuration shared by the submit and allocation wrappers.

TRAINING_ENV_NAMES=(
    MODEL_PRESET DATASET_PRESET INPUT_KEY LABEL_KEY APPLY_CHAT_TEMPLATE
    PROJECT_NAME EXPERIMENT_NAME MODEL_NAME HF_MODEL_NAME MODEL_PROFILE DATASET_TAG PROMPT_DATA
    PROMPT_DATA_CONFIG PROMPT_DATA_FILES PROMPT_DATA_RATIOS PROMPT_DATA_EPOCH_SIZE
    RUN_NAME CKPT_PATH PLACEMENT GPUS_PER_NODE ACTOR_NUM_NODES ACTOR_GPUS_PER_NODE
    ROLLOUT_NUM_GPUS ROLLOUT_NUM_GPUS_PER_ENGINE ROLLOUT_EXPERT_PARALLEL_SIZE TENSOR_PARALLEL_SIZE
    CONTEXT_PARALLEL_SIZE PIPELINE_PARALLEL_SIZE EXPERT_PARALLEL_SIZE EXPERT_TENSOR_PARALLEL_SIZE
    MEGATRON_TO_HF_MODE MAX_TOKENS_PER_GPU TRAINING_ATTENTION_BACKEND
    SGLANG_MEM_FRACTION SGLANG_MAX_RUNNING_REQUESTS
    LR NUM_ROLLOUT TRAIN_SEED ROLLOUT_SEED MAX_RESPONSE_LEN MAX_CONTEXT_LEN
    ROLLOUT_BATCH_SIZE N_SAMPLES_PER_PROMPT GLOBAL_BATCH_SIZE NUM_STEPS_PER_ROLLOUT
    SKIP_ACTOR_FORWARD_ONLY USE_ROLLOUT_ROUTING_REPLAY ENTROPY_COEF EPS_CLIP EPS_CLIP_HIGH
    IS_CORRECTION TIS_CLIP TIS_CLIP_LOW RM_TYPE RM_NUM_WORKERS LOG_ROLLOUT_EVENT_LOOP LOG_ROLLOUT_POSTPROCESS DYNAMIC_SAMPLING_FILTER_PATH
    MAX_WEIGHT_STALENESS ASYNC_MAX_CONCURRENT_SAMPLES
    ASYNC_DATA_BUFFER_CAPACITY_FACTOR ASYNC_UNUSED_SAMPLES_HANDLER
    ASYNC_DATA_BUFFER_ORDER ASYNC_STALENESS_METRIC CUSTOM_STALENESS_FUNCTION_PATH
    USE_REPLAY_DATA_BUFFER REPLAY_DATA_BUFFER_ASYNC_RESTORE REPLAY_DATA_BUFFER_MODE
    USE_REPLAY_BUFFER REPLAY_BUFFER_ASYNC_RESTORE
    LOG_ROLLOUT_REPETITION LOG_CATEGORY_STALENESS LOG_POLICY_LAG_METRICS SGLANG_RESPONSE_WEIGHT_VERSION_SEGMENTS
    PAUSE_GENERATION_MODE UPDATE_WEIGHT_TRANSFER_MODE
    HF_SAVE_INTERVAL SAVE_INTERVAL SAVE_RETAIN_INTERVAL SAVE_HF USE_CHECKPOINT_OPT_PARAM_SCHEDULER
    NEMO_GYM_ENDPOINTS NEMO_GYM_REQUEST_TIMEOUT TAU_USER_MODEL_CONFIG
    DUMP_ROLLOUT_DATA CLEAN_CHECKPOINT TRUNCATION_MODE
    EVAL_INTERVAL
    WANDB_MODE WANDB_TEAM WANDB_PROJECT
    MILES_LAUNCH_DRY_RUN RAY_JOIN_TIMEOUT RAY_PORT MILES_NCCL_TRANSPORT
)

miles_check_pending_features() {
    local name
    for name in USE_STALENESS_AWARE_LOSS; do
        if [[ "${!name:-0}" != 0 ]]; then
            echo "${name} was deferred; decide its migration before enabling it" >&2
            return 2
        fi
    done
    for name in QUEUE_TYPE QUEUE_FACTOR TRAINING_BUFFER_QUEUE_SIZE STALENESS_REFERENCE; do
        if [[ -n "${!name:-}" ]]; then
            echo "${name} is a source-branch override; see notes/agents/training-scripts.md" >&2
            return 2
        fi
    done
}

miles_training_defaults() {
    miles_check_pending_features || return
    : "${PLACEMENT:?choose disaggregate or colocated}"
    : "${MODEL_NAME:?select a model preset or set MODEL_NAME}"
    : "${HF_MODEL_NAME:?select a model preset or set HF_MODEL_NAME}"
    : "${MODEL_PROFILE:?select a model preset or set MODEL_PROFILE}"
    : "${DATASET_TAG:?select a dataset preset or set DATASET_TAG}"
    if [[ -z "${PROMPT_DATA_FILES:-}${PROMPT_DATA_CONFIG:-}" ]]; then
        : "${PROMPT_DATA:?select a dataset preset or set PROMPT_DATA}"
    fi
    : "${INPUT_KEY:=prompt}"
    : "${LABEL_KEY:=label}"
    : "${GPUS_PER_NODE:=8}"
    : "${ACTOR_GPUS_PER_NODE:=${GPUS_PER_NODE}}"
    if [[ "${PLACEMENT}" == disaggregate ]]; then
        : "${ACTOR_NUM_NODES:=1}"
        : "${ROLLOUT_NUM_GPUS:=$(( (MILES_JOB_NUM_NODES - ACTOR_NUM_NODES) * GPUS_PER_NODE ))}"
        : "${ROLLOUT_NUM_GPUS_PER_ENGINE:=1}"
        : "${SGLANG_MEM_FRACTION:=0.70}"
    else
        : "${ACTOR_NUM_NODES:=${MILES_JOB_NUM_NODES}}"
        : "${ROLLOUT_NUM_GPUS:=0}"
        : "${ROLLOUT_NUM_GPUS_PER_ENGINE:=2}"
        : "${SGLANG_MEM_FRACTION:=0.65}"
    fi
    : "${TENSOR_PARALLEL_SIZE:=2}"
    : "${CONTEXT_PARALLEL_SIZE:=1}"
    : "${PIPELINE_PARALLEL_SIZE:=1}"
    : "${EXPERT_PARALLEL_SIZE:=1}"
    : "${EXPERT_TENSOR_PARALLEL_SIZE:=1}"
    : "${MEGATRON_TO_HF_MODE:=raw}"
    : "${TRAINING_ATTENTION_BACKEND:=fused}"
    : "${MAX_TOKENS_PER_GPU:=32768}"
    : "${LR:=1e-6}"
    : "${NUM_ROLLOUT:=300}"
    : "${TRAIN_SEED:=1234}"
    : "${ROLLOUT_SEED:=42}"
    : "${MAX_RESPONSE_LEN:=16384}"
    : "${MAX_CONTEXT_LEN:=32768}"
    : "${ROLLOUT_BATCH_SIZE:=192}"
    : "${N_SAMPLES_PER_PROMPT:=16}"
    : "${GLOBAL_BATCH_SIZE:=3072}"
    : "${NUM_STEPS_PER_ROLLOUT:=1}"
    : "${SKIP_ACTOR_FORWARD_ONLY:=1}"
    : "${ENTROPY_COEF:=0.00}"
    : "${EPS_CLIP:=0.2}"
    : "${EPS_CLIP_HIGH:=0.28}"
    : "${IS_CORRECTION:=tis}"
    : "${TIS_CLIP:=2.0}"
    : "${TIS_CLIP_LOW:=0}"
    : "${RM_TYPE:=deepscaler}"
    : "${MAX_WEIGHT_STALENESS:=8}"
    : "${ASYNC_DATA_BUFFER_CAPACITY_FACTOR:=30}"
    : "${ASYNC_UNUSED_SAMPLES_HANDLER:=retry}"
    : "${ASYNC_DATA_BUFFER_ORDER:=fifo}"
    if [[ "${PLACEMENT}" == disaggregate ]]; then
        : "${ASYNC_STALENESS_METRIC:=first-prefill}"
    else
        : "${ASYNC_STALENESS_METRIC:=oldest}"
    fi
    : "${CUSTOM_STALENESS_FUNCTION_PATH:=}"
    # Legacy environment names are accepted at the launcher boundary; new names win.
    : "${USE_REPLAY_DATA_BUFFER:=${USE_REPLAY_BUFFER:-0}}"
    : "${REPLAY_DATA_BUFFER_ASYNC_RESTORE:=${REPLAY_BUFFER_ASYNC_RESTORE:-0}}"
    : "${REPLAY_DATA_BUFFER_MODE:=rollout}"
    : "${LOG_ROLLOUT_REPETITION:=0}"
    : "${LOG_CATEGORY_STALENESS:=0}"
    : "${LOG_POLICY_LAG_METRICS:=0}"
    : "${SGLANG_RESPONSE_WEIGHT_VERSION_SEGMENTS:=1}"
    : "${PAUSE_GENERATION_MODE:=in_place}"
    : "${UPDATE_WEIGHT_TRANSFER_MODE:=broadcast}"
    : "${SAVE_INTERVAL:=10}"
    : "${SAVE_RETAIN_INTERVAL:=100}"
    : "${SAVE_HF:=1}"
    : "${HF_SAVE_INTERVAL:=}"
    : "${USE_CHECKPOINT_OPT_PARAM_SCHEDULER:=1}"
    : "${DUMP_ROLLOUT_DATA:=0}"
    : "${CLEAN_CHECKPOINT:=0}"
    : "${TRUNCATION_MODE:=none}"
    : "${EVAL_INTERVAL:=0}"
    : "${WANDB_MODE:=online}"
    : "${WANDB_PROJECT:=miles-v0.1.1-abci-math}"
    export PLACEMENT
    local name
    for name in "${TRAINING_ENV_NAMES[@]}"; do
        [[ ! -v "${name}" ]] || export "${name}"
    done
}
