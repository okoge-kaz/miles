#!/bin/bash

_miles_job_env_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
source "${_miles_job_env_dir}/training_config.sh"
unset _miles_job_env_dir

miles_job_export_spec() {
    local name
    local -a names=()
    for name in \
        MILES_REPO MILES_WORKSPACE_ROOT CHECKPOINT_ROOT HF_CKPT_DIR MEGATRON_CKPT_DIR \
        TRAIN_CKPT_DIR DATASET_ROOT RL_DATASET_DIR PRETRAIN_DATASET_DIR SFT_DATASET_DIR \
        CONTAINER_DIR CONTAINER_IMAGE CACHE_DIR DOCKER_IMAGE \
        QWEN3_4B_BASE_HF_MODEL QWEN3_8B_BASE_HF_MODEL QWEN3_30B_A3B_BASE_HF_MODEL \
        PBS_PROJECT PBS_GPU_QUEUE PBS_CPU_QUEUE PBS_GPU_RESOURCE_TYPE PBS_CPU_RESOURCE_TYPE \
        PBS_GPU_CPUS_PER_NODE PBS_GPU_GPUS_PER_NODE PBS_CPU_CPUS_PER_NODE ABCI_HPCX_MODULE ABCI_PYTHON_MODULE \
        PBS_DEFAULT_WALLTIME PBS_CONTAINER_WALLTIME PBS_PREP_WALLTIME \
        SINGULARITY_BIN MPIRUN_BIN IMPORT_OUTPUT_IMAGE SINGULARITY_LINK \
        APPLY_SGLANG_PROVENANCE_PATCH INSTALL_CODE_SANDBOX INSTALL_NEMO_GYM \
        DATASET_NUM_PROC DATASET_CHUNK_SIZE \
        JUDGE_RUN_NAME JUDGE_MODEL_PATH JUDGE_MODEL_REVISION JUDGE_MODEL_NAME JUDGE_STATE_DIR \
        JUDGE_ADVERTISE_HOST JUDGE_PORT JUDGE_TP_SIZE JUDGE_CONTEXT_LENGTH JUDGE_MEM_FRACTION \
        JUDGE_MAX_RUNNING_REQUESTS JUDGE_STARTUP_TIMEOUT \
        CONVERT_INPUT_DIR CONVERT_OUTPUT_DIR CONVERT_ORIGIN_HF_DIR CONVERT_CHUNK_SIZE CONVERT_VOCAB_SIZE \
        CONVERT_MODEL_PRESET MODEL_VARIANT CONVERT_BACKEND HF_BASE_REF HF_RL_REF HF_SFT_REF MODEL_SFT_NAME \
        CONVERT_TENSOR_PARALLEL_SIZE CONVERT_PIPELINE_PARALLEL_SIZE CONVERT_EXPERT_PARALLEL_SIZE \
        "${TRAINING_ENV_NAMES[@]}"; do
        [[ ! -v "${name}" ]] || names+=("${name}")
    done
    local IFS=,
    printf '%s\n' "${names[*]}"
}
